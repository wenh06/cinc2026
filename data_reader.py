def download_with_resume_using_pycurl(url: str, output_path: str, retries: int = 3) -> None:
    try:
        import pycurl
    except ImportError:
        raise ImportError("pycurl is required for this download method.")

    output_path = Path(output_path)  # type: ignore
    temp_file = output_path

    existing_size = temp_file.stat().st_size if temp_file.exists() else 0

    for attempt in range(retries):
        try:
            with open(temp_file, "ab") as f:
                c = pycurl.Curl()

                c.setopt(pycurl.URL, url)
                c.setopt(pycurl.WRITEDATA, f)
                c.setopt(pycurl.FOLLOWLOCATION, True)  # -L
                c.setopt(pycurl.NOPROGRESS, False)

                if existing_size > 0:
                    c.setopt(pycurl.RESUME_FROM_LARGE, existing_size)

                def progress(total, downloaded, upload_total, uploaded):
                    if total > 0:
                        percent = downloaded / total * 100
                        bar_len = 40
                        filled = int(bar_len * downloaded // total)
                        bar = "=" * filled + "-" * (bar_len - filled)
                        sys.stdout.write(f"\r[{bar}] {percent:6.2f}% " f"{downloaded/1024/1024:.1f}/{total/1024/1024:.1f} MB")
                        sys.stdout.flush()

                c.setopt(pycurl.XFERINFOFUNCTION, progress)

                c.perform()
                c.close()

            print("\nDownload completed.")
            return

        except pycurl.error as e:
            print(f"\nError: {e}, retrying ({attempt+1}/{retries})...")
            time.sleep(2)

    raise RuntimeError("Download failed after retries")
